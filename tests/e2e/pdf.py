"""v0.9: importar sequência a partir do PDF da OS (PDFs FICTÍCIOS gerados por tests/fixtures/gerar_pdfs.py)."""
import sys, pathlib, re
from playwright.sync_api import sync_playwright
URL = pathlib.Path('dist/index.html').resolve().as_uri()
FIX = pathlib.Path('tests/fixtures')
SHOTS = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else None
res = []
def ok(n, c): res.append(('PASSOU' if c else 'FALHOU', n)); return c

def rodar(vp, rot, mobile=False):
    with sync_playwright() as p:
        b = p.chromium.launch()
        ctx = b.new_context(viewport=vp, is_mobile=mobile, has_touch=mobile)
        pg = ctx.new_page(); erros = []; pg.on('pageerror', lambda e: erros.append(str(e)))
        rede = []; pg.on('request', lambda r: rede.append(r.url) if not r.url.startswith(('file:', 'blob:', 'data:')) and 'fonts.g' not in r.url else None)
        ds = lambda: pg.evaluate("JSON.parse(localStorage.getItem('dap-proto-v1:dataset'))")
        def ir(h): pg.goto(URL + '#/' + h); pg.wait_for_timeout(250)
        pg.goto(URL); pg.wait_for_selector('.destaque-valor')
        ir('configuracoes'); pg.click('[data-acao="base-propria"]'); pg.click('[data-ok]'); pg.wait_for_url(re.compile('#/fazendas')); pg.wait_for_selector('#fz-tab')
        pg.click('[data-novo="unidade"]'); pg.fill('.modal [name="nome"]', 'Unidade T'); pg.fill('.modal [name="codigo"]', 'UT'); pg.click('.modal [data-salvar]'); pg.wait_for_timeout(150)
        ir('relatorios/sequencia'); pg.click('[data-acao="importar"]')
        ok(f'[{rot}] importar sequência tem a aba PDF da OS', pg.locator('[data-imp="aba-pdf"]').count() == 1)
        pg.click('[data-imp="aba-pdf"]'); pg.wait_for_selector('.pdf-zona')
        pg.set_input_files('[data-imp="arquivos"]', [str(FIX / 'OS 3410 - FN 094-095 (ficticia).pdf'), str(FIX / 'OS 3416 - FN 090 (ficticia).pdf'), str(FIX / 'OS 9999 - digitalizada (ficticia).pdf')])
        pg.wait_for_function("document.querySelectorAll('.pdf-item').length === 3 && !document.querySelector('.pdf-item .selo-info')", timeout=60000)
        itens = pg.locator('.pdf-item')
        t1 = itens.nth(0).inner_text()
        ok(f'[{rot}] PDF 3410: OS, FN 94 e 95, 5 talhões, soma 64,45 = total (confere), Tratamento 1 com 6 produtos', all(x in t1 for x in ['3410', '94, 95', 'Talhões\n5', '64,45', 'confere', 'Tratamento 1 · 6 produto']) or all(x in t1.replace('\n', ' ') for x in ['3410', '94, 95', '64,45', 'confere', '6 produto']))
        itens.nth(0).locator('summary', has_text='Talhões extraídos').click()
        tt = itens.nth(0).locator('table').inner_text()
        ok(f'[{rot}] talhões extraídos com fazenda, zona e área', 'SITIO EXEMPLO A' in tt and '12,33' in tt and '31,75' in tt and '91' in tt)
        t2 = itens.nth(1).inner_text().replace('\n', ' ')
        ok(f'[{rot}] PDF 3416: FN 90, 3 talhões, "Área total" 32,70 confere', '3416' in t2 and '90' in t2 and '32,70' in t2 and 'confere' in t2)
        t3 = itens.nth(2).inner_text()
        ok(f'[{rot}] PDF digitalizado: aviso de que não há texto', 'sem texto' in t3)
        ok(f'[{rot}] com erro em um arquivo, importar fica bloqueado', pg.locator('[data-imp="confirmar"]').is_disabled())
        itens.nth(2).locator('[data-pdf-rem]').click(); pg.wait_for_timeout(100)
        pg.fill('[data-imp="nome"]', 'Fungicida PDF'); pg.select_option('[data-imp="tipo"]', 'Fungicida'); pg.wait_for_timeout(200)
        btn = pg.locator('[data-imp="confirmar"]').inner_text()
        ok(f'[{rot}] prévia: 3 OS (3410 vira 2 por FN) · 97,15 ha', '3 OS' in btn and '97,15' in btn)
        if SHOTS: pg.locator('.modal').screenshot(path=str(SHOTS / f'{rot}-importar-pdf.png'))
        pg.click('[data-imp="confirmar"]'); pg.wait_for_selector('#seq-tab tbody tr'); pg.wait_for_timeout(250)
        d = ds()
        ok(f'[{rot}] 3 fazendas e 3 OS criadas; 8 talhões reais', len(d['fazendas']) == 3 and len(d['ordens']) == 3 and len(d['talhoes']) == 8 and not any(t.get('geral') for t in d['talhoes']))
        areas = sorted(round(sum(i['areaPlanejadaHa'] for i in o['itens']), 2) for o in d['ordens'])
        ok(f'[{rot}] áreas por OS: 27,40 · 32,70 · 37,05', areas == [27.4, 32.7, 37.05])
        ok(f'[{rot}] tratamento virou calda com 6 produtos e códigos', len(d['produtos']) == 6 and all(p.get('codigo') for p in d['produtos']) and all(len(o['calda']['produtos']) == 6 for o in d['ordens'] if o['numero'] == '3410'))
        ok(f'[{rot}] sequência mostra 97,15 ha programados', '97,15' in pg.locator('.seq-nums').inner_text())
        ok(f'[{rot}] leitura 100% local (nenhum acesso à rede)', not rede)
        ok(f'[{rot}] sem erros de JavaScript', not erros)
        if erros: print(erros)
        if rede: print(rede)
        b.close()

rodar({'width': 1440, 'height': 900}, 'desktop')
rodar({'width': 390, 'height': 844}, 'iphone', True)
for s, n in res: print(f'{s}  {n}')
print(f"\n{sum(1 for s,_ in res if s=='PASSOU')}/{len(res)} verificações passaram")
sys.exit(0 if all(s == 'PASSOU' for s, _ in res) else 1)
