"""Teste ponta a ponta: validações do formulário, gravação, persistência e reflexo no dashboard e nos filtros."""
import sys, pathlib, re
from playwright.sync_api import sync_playwright, expect
URL = pathlib.Path('dist/index.html').resolve().as_uri() + '?modo=local'  # sem nuvem nos testes de tela
SHOTS = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else None
res = []
def ok(nome, cond): res.append(('PASSOU' if cond else 'FALHOU', nome)); return cond
def kpi_area(pg): return pg.locator('.destaque-valor').inner_text()

def rodar(vp, rotulo, mobile=False):
    with sync_playwright() as p:
        b = p.chromium.launch(); ctx = b.new_context(viewport=vp, is_mobile=mobile, has_touch=mobile, locale='pt-BR'); pg = ctx.new_page()
        erros = []; pg.on('pageerror', lambda e: erros.append(str(e)))
        pg.goto(URL); pg.wait_for_selector('.destaque-valor')
        area0 = kpi_area(pg)
        # filtro global reage
        if mobile: pg.click('.filtros-toggle')
        pg.select_option('select[data-f="unidadeId"]', 'un-s'); pg.wait_for_timeout(200)
        ok(f'[{rotulo}] filtro por unidade altera indicadores', kpi_area(pg) != area0)
        pg.click('.btn-limpar'); pg.wait_for_timeout(200)
        ok(f'[{rotulo}] limpar filtros restaura indicadores', kpi_area(pg) == area0)
        n_ops0 = pg.evaluate("JSON.parse(localStorage.getItem('dap-proto-v1:dataset')).operacoes.length")

        pg.select_option('select[data-f="turnoId"]', 'tn-a'); pg.wait_for_timeout(150); area_a = kpi_area(pg)
        pg.select_option('select[data-f="turnoId"]', 'tn-b'); pg.wait_for_timeout(150); area_b = kpi_area(pg)
        num = lambda t: float(t.replace('ha','').replace('.','').replace(',','.').strip())
        ok(f'[{rotulo}] filtro por turno: A + B = total', abs(num(area_a) + num(area_b) - num(area0)) < 0.15)
        pg.click('.btn-limpar'); pg.wait_for_timeout(150)
        pg.goto(URL + '#/turnos'); pg.wait_for_selector('#tn-tab tbody tr')
        ok(f'[{rotulo}] tela Turnos e líderes lista 3 turnos', pg.locator('#tn-tab tbody tr').count() == 3)
        pg.goto(URL + '#/aplicacoes/nova'); pg.wait_for_selector('#wz-form')
        av = pg.locator('[data-acao="avancar"]')
        av.click(); ok(f'[{rotulo}] etapa 1 vazia é bloqueada', pg.locator('.aviso-critico').count() > 0)
        pg.fill('[data-k="data"]', '2026-12-31'); pg.fill('[data-k="horaInicio"]', '19:00')
        pg.select_option('[data-k="turnoId"]', 'tn-a')
        ok(f'[{rotulo}] líder preenchido pelo turno', pg.locator('[data-k="liderId"]').input_value() == 'ld-1')
        pg.select_option('[data-k="liderId"]', 'ld-3')
        pg.select_option('[data-k="unidadeId"]', 'un-n'); pg.select_option('[data-k="fazendaId"]', 'fz-6')
        os_val = pg.locator('[data-k="osId"] option').nth(1).get_attribute('value'); pg.select_option('[data-k="osId"]', os_val)
        livres = pg.locator('.talhao-op:not(.concluido) input'); livres.nth(0).check(); pg.locator('.talhao-op:not(.concluido) input').nth(1).check()
        av.click(); ok(f'[{rotulo}] data futura é bloqueada', 'futuro' in pg.locator('#wz-msgs').inner_text())
        pg.fill('[data-k="data"]', '2026-10-19'); pg.locator('[data-k="data"]').dispatch_event('change')
        av.click(); ok(f'[{rotulo}] avança para etapa 2', 'Etapa 2' in pg.locator('#wz-pos').inner_text())
        pg.select_option('[data-k="aeronaveId"]', 'ac-1'); pg.select_option('[data-k="pilotoId"]', 'pl-1')
        pg.locator('[data-aux="ax-1"]').check()
        av.click(); ok(f'[{rotulo}] avança para etapa 3', 'Etapa 3' in pg.locator('#wz-pos').inner_text())
        a0 = pg.locator('[data-k="itens.0.areaHa"]')
        a0.fill('-5'); av.click(); ok(f'[{rotulo}] área negativa é bloqueada', 'negativa' in pg.locator('#wz-msgs').inner_text())
        a0.fill('12,5'); pg.fill('[data-k="itens.1.areaHa"]', '9.75')
        pg.fill('[data-k="produtos.0.doseReal"]', '0,41')
        ok(f'[{rotulo}] área total calculada (22,25 ha)', '22,25' in pg.locator('#calc-area').inner_text())
        ok(f'[{rotulo}] volume total de calda (445 L)', '445' in pg.locator('#calc-vol').inner_text())
        ok(f'[{rotulo}] quantidade total do produto (9,12 L)', '9,12' in pg.locator('[data-qtd="0"]').inner_text())
        av.click(); ok(f'[{rotulo}] avança para etapa 4', 'Etapa 4' in pg.locator('#wz-pos').inner_text())
        pg.click('[data-acao="add-clima"]')
        pg.fill('[data-k="clima.0.ventoKmh"]', '14'); pg.fill('[data-k="clima.0.umidadePct"]', '70'); pg.fill('[data-k="clima.0.temperaturaC"]', '24')
        ok(f'[{rotulo}] leitura fora do limite sinalizada', 'Fora dos limites' in pg.locator('[data-clima="0"]').inner_text())
        av.click(); ok(f'[{rotulo}] origem da leitura é obrigatória', 'origem' in pg.locator('#wz-msgs').inner_text().lower())
        pg.fill('[data-k="clima.0.origem"]', 'Estação portátil')
        av.click(); ok(f'[{rotulo}] avança para etapa 5', 'Etapa 5' in pg.locator('#wz-pos').inner_text())
        pg.fill('[data-k="horaFim"]', '00:30'); pg.locator('[data-k="horaFim"]').dispatch_event('change')
        ok(f'[{rotulo}] tempo total com virada do dia (5h 30min)', '5h 30min' in pg.locator('#calc-total').inner_text())
        pg.click('[data-acao="add-parada"]')
        pg.select_option('[data-k="paradas.0.motivo"]', 'Vento acima do limite')
        pg.fill('[data-k="paradas.0.inicio"]', '21:00'); pg.fill('[data-k="paradas.0.fim"]', '21:40')
        pg.fill('[data-k="tempoEfetivoMin"]', '300'); pg.fill('[data-k="responsavelEncerramento"]', 'André Moraes')
        av.click(); ok(f'[{rotulo}] efetivo + paradas > total é bloqueado', 'excede' in pg.locator('#wz-msgs').inner_text())
        pg.fill('[data-k="tempoEfetivoMin"]', '240')
        av.click(); ok(f'[{rotulo}] chega à revisão', 'Etapa 6' in pg.locator('#wz-pos').inner_text())
        ok(f'[{rotulo}] revisão lista ponto de conferência do clima', 'Fora dos limites' in pg.locator('#wz-form').inner_text())
        if SHOTS: pg.screenshot(path=str(SHOTS / f'{rotulo}-revisao.png'), full_page=True)
        # rascunho sobrevive a recarregar
        pg.reload(); pg.wait_for_selector('#wz-form')
        ok(f'[{rotulo}] rascunho preservado após recarregar', 'Etapa 6' in pg.locator('#wz-pos').inner_text())
        pg.locator('[data-acao="avancar"]').click(); pg.wait_for_url(re.compile('#/aplicacoes$'))
        pg.wait_for_selector('.selo-novo', timeout=5000)
        ok(f'[{rotulo}] registro aparece na lista', pg.locator('.selo-novo').count() >= 1)
        nova = pg.evaluate("JSON.parse(localStorage.getItem('dap-proto-v1:dataset')).operacoes.find(o => o.origem === 'registro_prototipo')")
        ok(f'[{rotulo}] turno e líder substituto gravados', nova['turnoId'] == 'tn-a' and nova['liderId'] == 'ld-3')
        n_ops1 = pg.evaluate("JSON.parse(localStorage.getItem('dap-proto-v1:dataset')).operacoes.length")
        ok(f'[{rotulo}] exatamente 1 operação gravada', n_ops1 == n_ops0 + 1)
        pg.reload(); pg.wait_for_selector('.tabela')
        ok(f'[{rotulo}] persiste após recarregar', pg.locator('.selo-novo').count() >= 1)
        pg.goto(URL + '#/dashboard'); pg.wait_for_selector('.destaque-valor')
        def num(t): return float(t.replace('ha','').replace('.','').replace(',','.').strip())
        ok(f'[{rotulo}] acumulado do dashboard +22,25 ha', abs(num(kpi_area(pg)) - num(area0) - 22.25) < 0.06)
        pg.locator('.op-linha').first.click(); pg.wait_for_selector('.modal')
        ok(f'[{rotulo}] detalhe técnico abre', 'Calda e produtos' in pg.locator('.modal').inner_text())
        if SHOTS: pg.screenshot(path=str(SHOTS / f'{rotulo}-detalhe.png'))
        pg.keyboard.press('Escape')
        # previsão de término
        pg.goto(URL + '#/dashboard'); pg.wait_for_selector('.previsao')
        txt = pg.locator('.prev-data').inner_text()
        ok(f'[{rotulo}] previsão mostra uma data', re.match(r'\d{2}/\d{2}/\d{4}', txt) is not None)
        rc = pg.locator('.previsao').inner_text()
        pg.select_option('[data-acao="base-previsao"]', '7'); pg.wait_for_timeout(150)
        ok(f'[{rotulo}] janela-base de 7 dias recalcula', '7 (' in pg.locator('.previsao').inner_text() and pg.locator('.previsao').inner_text() != rc)
        pg.select_option('[data-acao="base-previsao"]', 'periodo'); pg.wait_for_timeout(150)
        if mobile: pg.click('.filtros-toggle')
        pg.select_option('select[data-f="campanhaId"]', 'cp-mat'); pg.wait_for_timeout(150)
        ok(f'[{rotulo}] com campanha filtrada compara com o prazo', '15/11/2026' in pg.locator('.previsao').inner_text() and 'ha/dia' in pg.locator('.previsao').inner_text())
        ok(f'[{rotulo}] projeção estende o gráfico de evolução', pg.locator('#g-evolucao path[stroke-dasharray="2 4"]').count() == 1)
        pg.click('.btn-limpar'); pg.wait_for_timeout(100)
        # diário de aplicações
        pg.goto(URL + '#/relatorios/diario'); pg.wait_for_selector('.dia-cab')
        area_dia = pg.locator('.dia-total b').first.inner_text()
        ok(f'[{rotulo}] diário abre no último dia com operação', pg.locator('.dia-faz').count() >= 1 and 'ha' in area_dia)
        d0 = pg.locator('.dia-data input').input_value(); pg.click('[data-nav="ant"]'); pg.wait_for_timeout(120)
        ok(f'[{rotulo}] diário navega para o dia anterior', pg.locator('.dia-data input').input_value() < d0)
        ok(f'[{rotulo}] linha do tempo gerada das paradas', pg.locator('.dia-tempo .ev').count() >= 2)
        pg.select_option('[data-k="turnoId"]', 'tn-c'); pg.wait_for_timeout(120)
        ok(f'[{rotulo}] turno sem operação mostra aviso (sem dados inventados)', pg.locator('.dia-faz').count() == 0)
        pg.select_option('[data-k="turnoId"]', ''); pg.wait_for_timeout(100)
        pg.goto(URL + '#/dashboard'); pg.wait_for_selector('#g-dia svg')
        # meta operacional
        ok(f'[{rotulo}] linha de meta no gráfico diário (384 ha/dia)', '384 ha/dia' in pg.locator('#g-dia').locator('xpath=..').inner_text() and pg.locator('#g-dia path[stroke-dasharray]').count() == 1)
        ok(f'[{rotulo}] linha de meta no gráfico semanal (2.688 ha/semana)', '2.688 ha/semana' in pg.locator('#g-semana').locator('xpath=..').inner_text())
        ok(f'[{rotulo}] ritmo planejado na evolução', 'Ritmo planejado' in pg.locator('#g-evolucao').locator('xpath=..').inner_text())
        pg.goto(URL + '#/configuracoes'); pg.wait_for_selector('#resumo-meta table')
        res_txt = pg.locator('#resumo-meta').inner_text()
        ok(f'[{rotulo}] prévia por drone 192 / 1.344', '192 ha' in res_txt and '1.344 ha' in res_txt)
        pg.fill('[name="dronesPorTurno"]', '2'); pg.locator('[name="dronesPorTurno"]').dispatch_event('input')
        res_txt = pg.locator('#resumo-meta').inner_text()
        ok(f'[{rotulo}] 2 drones nos 2 turnos = 768 / 5.376', '768 ha' in res_txt and '5.376 ha' in res_txt)
        pg.fill('[name="dronesPorTurno"]', '3'); pg.locator('[name="dronesPorTurno"]').dispatch_event('input')
        ok(f'[{rotulo}] parâmetro inválido bloqueado', 'não pode ser maior' in pg.locator('#resumo-meta').inner_text())
        pg.fill('[name="dronesPorTurno"]', '2'); pg.locator('#form-meta button[type=submit]').click(); pg.wait_for_timeout(150)
        pg.goto(URL + '#/dashboard'); pg.wait_for_selector('#g-dia svg')
        ok(f'[{rotulo}] meta salva reflete no dashboard (768 ha/dia)', '768 ha/dia' in pg.locator('#g-dia').locator('xpath=..').inner_text())
        if mobile: pg.click('.filtros-toggle')
        pg.select_option('select[data-f="aeronaveId"]', 'ac-1'); pg.wait_for_timeout(150)
        ok(f'[{rotulo}] filtro por drone recorta a meta (384 ha/dia)', '384 ha/dia' in pg.locator('#g-dia').locator('xpath=..').inner_text())
        pg.click('.btn-limpar'); pg.wait_for_timeout(100)
        # restaurar demo com confirmação
        pg.goto(URL + '#/configuracoes'); pg.click('[data-acao="restaurar"]'); pg.click('[data-ok]'); pg.wait_for_timeout(200)
        n_ops2 = pg.evaluate("JSON.parse(localStorage.getItem('dap-proto-v1:dataset')).operacoes.length")
        ok(f'[{rotulo}] restaurar demonstração (com confirmação)', n_ops2 == n_ops0)
        chaves = pg.evaluate("Object.keys(localStorage)")
        ok(f'[{rotulo}] só usa chaves com prefixo próprio', all(k.startswith('dap-proto-v1:') for k in chaves))
        ok(f'[{rotulo}] sem erros de JavaScript', not erros)
        if erros: print(erros)
        b.close()

rodar({'width': 1440, 'height': 900}, 'desktop')
rodar({'width': 390, 'height': 844}, 'iphone', mobile=True)
for s, n in res: print(f'{s}  {n}')
print(f"\n{sum(1 for s,_ in res if s=='PASSOU')}/{len(res)} verificações passaram")
sys.exit(0 if all(s == 'PASSOU' for s, _ in res) else 1)
